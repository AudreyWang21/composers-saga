def fetch():
    try:
        req = Request(URL, headers={"User-Agent": "composer-meme-machine"})
        d = json.loads(urlopen(req, timeout=5).read().decode("utf-8"))
        if all(d.get(k) for k in WORDS):
            return d
    except Exception:
        pass
    return None


def one(w):
    a, b = random.sample(w["音乐家"], 2)  # two different composers
    return (random.choice(w["情景"]) + a + "和" + b
            + random.choice(w["怎么样地"]) + random.choice(w["做什么"]) + "。")


if __name__ == "__main__":
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass
    args = sys.argv[1:]
    words = WORDS
    if "--fetch" in args:
        args.remove("--fetch")
        words = fetch() or WORDS
    n = int(args[0]) if args and args[0].isdigit() else 1
    for _ in range(max(1, n)):
        print(one(words))
